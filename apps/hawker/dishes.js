// Communities behind a dish, for the rojak meter: "Malay and Javanese" counts for both.
export function communitiesOf(dishId) {
  const c = DISHES[dishId]?.community ?? "";
  if (/shared by all/i.test(c)) return ["Shared by all"];
  return c.split(/ and |, /).map((x) => x.trim()).filter(Boolean);
}

export function partsOf(dishId, variant) {
  const d = DISHES[dishId];
  if (!d) return [];
  return (d.variants[variant] ?? Object.values(d.variants)[0]).parts;
}

export function variantLabel(dishId, variant) {
  return DISHES[dishId]?.variants[variant]?.label ?? "";
}

