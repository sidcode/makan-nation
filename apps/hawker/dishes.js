const STEP_WORDS = {
  steam: "steamed",
  poach: "poached",
  roast: "roasted",
  braise: "braised",
  chop: "sliced",
  toast: "toasted",
  grill: "grilled",
  fry: "fried",
  boil: "boiled",
  shave: "shaved",
  simmer: "simmered",
  press: "pressed",
  spread: "spread with kaya and butter",
};

// Plain words for a component, e.g. "Chicken, poached + sliced".
export function componentLabel(sig) {
  const [kind, steps] = sig.split("|");
  const words = (steps ? steps.split(",") : []).map((s) => STEP_WORDS[s] ?? s);
  const base = INGREDIENTS[kind]?.name ?? kind;
  if (kind === "bread" && steps?.includes("spread")) return "Kaya toast";
  if (kind === "bread" && words.includes("toasted")) return "Toast, no kaya yet";
  if (kind === "ice" && words.includes("shaved")) return "Shaved ice";
  if (kind === "chilli") return "Chilli on the side";
  if (kind === "puff" && words.includes("fried")) return "Curry puff, fried";
  if (kind === "ondeh" && words.length) return "Ondeh-ondeh";
  if (kind === "lapis" && words.length) return "Kueh lapis";
  if (kind === "thosai" && words.length) return "Thosai";
  if (kind === "banana" && words.length) return "Goreng pisang";
  if (kind === "chengtng" && words.length) return "Cheng tng";
  if (kind === "sugarcane" && words.length) return "Sugarcane juice";
  if (kind === "chicken" && words.includes("braised")) return `Soya sauce chicken${words.includes("sliced") ? ", sliced" : ""}`;
  return words.length ? `${base}, ${words.join(" + ")}` : base;
}

export function componentColor(sig) {
  return INGREDIENTS[sig.split("|")[0]]?.color ?? "#999";
}

